// Слепое сопоставление A/B в судье: какая из двух сторон — кандидат, а какая — прод.
//
// Требования к этой функции жёсткие, каждое ломало судью по-своему:
//
//  1. Воспроизводимость: порядок обязан определяться ТОЛЬКО от id кейса — судья не должен
//     знать автора, а повторный прогон обязан дать тот же порядок (иначе результаты
//     несравнимы между запусками).
//  2. Реальное перемешивание: зависимость от ОДНОГО символа (как было: charCodeAt(1))
//     на продовом корпусе даёт 0 из 100 кандидатов в одной стороне — все id вида `c0001`,
//     второй символ всегда `0`. Продовое письмо уезжало в «A» всегда, и судья со
//     врождённым предпочтением первой стороны стабильно играл против моделей-кандидатов.
//     Берём бит из всей строки.
//  3. Устойчивость к коротким/пустым id: charCodeAt(1) у строки из одного символа — undefined,
//     undefined % 2 === 1 — false, и кейс молча уезжает в одну сторону.
//
// Функция вынесена из скрипта в модуль, чтобы на неё лежал регрессионный тест:
// скрипт не импортируется в тест (у него есть побочный запуск на верхнем уровне).

/**
 * @param {string} caseId id кейса датасета
 * @returns {true|false} true — письмо кандидата идёт в A, прод в B; false — наоборот
 */
export function flipFor(caseId) {
  const id = typeof caseId === 'string' ? caseId : '';
  // FNV-1a: дешёвый, детерминированный, бит тянется из всех символов, а не из одного.
  let h = 0x811c9dc5;
  for (let i = 0; i < id.length; i++) {
    h ^= id.charCodeAt(i);
    h = Math.imul(h, 0x01000193);
  }
  return (h >>> 0) % 2 === 1;
}
